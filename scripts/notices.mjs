// Generates THIRD_PARTY_NOTICES.md from the production dependency tree.
// usage: node scripts/notices.mjs            (write)
//        node scripts/notices.mjs --check    (exit 1 if the committed file is stale)
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const raw = JSON.parse(execFileSync('pnpm', ['licenses', 'list', '--prod', '--json'], { encoding: 'utf8' }));
const rows = Object.entries(raw)
  .flatMap(([license, pkgs]) => pkgs.map((p) => ({ name: p.name, version: p.versions.join(', '), license, url: p.homepage ?? '' })))
  .sort((a, b) => a.name.localeCompare(b.name));

const body = [
  '# Third-party notices',
  '',
  'govSim bundles the following packages. Each keeps its own license; full texts ship in each',
  "package's directory under `node_modules` and at the linked homepages.",
  '',
  'Generated by `node scripts/notices.mjs`; do not edit by hand.',
  '',
  '| Package | Version | License | Homepage |',
  '|---|---|---|---|',
  ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.license} | ${r.url} |`),
  '',
].join('\n');

const file = 'THIRD_PARTY_NOTICES.md';
if (process.argv.includes('--check')) {
  if (!existsSync(file) || readFileSync(file, 'utf8') !== body) {
    console.error(`${file} is stale: run node scripts/notices.mjs`);
    process.exit(1);
  }
} else {
  writeFileSync(file, body);
  console.log(`${file}: ${rows.length} packages`);
}
